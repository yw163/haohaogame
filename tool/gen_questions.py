# ========== 组装 levels.json ==========
SUBJECT_META = [
    ("math", "数学", gen_math),
    ("space", "宇宙", gen_space),
    ("physics", "物理", gen_physics),
    ("fun", "趣味", gen_fun),
    ("poetry", "古诗词", gen_poetry),  # 古诗词放最后（较难）
]
PER_LEVEL = 5  # 每关题数

def build():
    levels = []
    global_index = 0
    for sub_id, sub_name, gen in SUBJECT_META:
        questions = gen()
        n_levels = len(questions) // PER_LEVEL  # 100/5 = 20
        for li in range(n_levels):
            global_index += 1
            chunk = questions[li * PER_LEVEL:(li + 1) * PER_LEVEL]
            is_boss = (li == n_levels - 1)  # 每科最后一关为 BOSS
            # 给题目补 id
            for qi, q in enumerate(chunk):
                q["id"] = f"{sub_id}_L{li+1:02d}_q{qi+1}"
            levels.append({
                "id": f"{sub_id}_L{li+1:02d}",
                "subject": sub_id,
                "indexInSubject": li + 1,
                "globalIndex": global_index,
                "title": f"{sub_name}第{li+1}关" + ("（大闯关）" if is_boss else ""),
                "emoji": "👑" if is_boss else "⭐",
                "isBoss": is_boss,
                "questions": chunk,
            })
    return levels

