# ---------- 工具 ----------
def sc(prompt, tts, opts, correct, emoji="", intro=None):
    """单选题。opts: list of (label) 或 (emoji,label)。correct: 正确项的下标"""
    options = []
    for i, o in enumerate(opts):
        oid = chr(97 + i)
        if isinstance(o, tuple):
            options.append({"id": oid, "emoji": o[0], "label": o[1]})
        else:
            options.append({"id": oid, "label": str(o)})
    q = {"type": "singleChoice", "prompt": prompt, "ttsText": tts,
         "emoji": emoji, "options": options,
         "correctIds": [chr(97 + correct)]}
    if intro:
        q["scienceIntro"] = intro
    return q

def ni(prompt, tts, answer, emoji=""):
    """数字输入题"""
    return {"type": "numberInput", "prompt": prompt, "ttsText": tts,
            "emoji": emoji, "options": [], "correctIds": [str(answer)]}

def mc(prompt, tts, opts, correct_ids, emoji=""):
    """多选题。opts: (emoji,label) list；correct_ids: 正确下标 list"""
    options = []
    for i, o in enumerate(opts):
        oid = chr(97 + i)
        if isinstance(o, tuple):
            options.append({"id": oid, "emoji": o[0], "label": o[1]})
        else:
            options.append({"id": oid, "label": str(o)})
    return {"type": "multiChoice", "prompt": prompt, "ttsText": tts,
            "emoji": emoji, "options": options,
            "correctIds": [chr(97 + i) for i in correct_ids]}

def num_opts(answer, spread=3):
    """围绕正确答案生成 3 个干扰项的单选"""
    cands = set()
    while len(cands) < 2:
        d = random.randint(-spread, spread)
        if d != 0 and answer + d >= 0:
            cands.add(answer + d)
    opts = list(cands) + [answer]
    random.shuffle(opts)
    return opts, opts.index(answer)


